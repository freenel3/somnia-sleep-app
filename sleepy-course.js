class SleepyCourseEngine {
  constructor() {
    this.currentDay = 1;
    this.completedDays = new Set([1]); // Day 1 completed initially
    this.loadProgress();
  }

  loadProgress() {
    try {
      const saved = localStorage.getItem('somnia_sleepy_course_progress');
      if (saved) {
        const data = JSON.parse(saved);
        this.currentDay = data.currentDay || 1;
        this.completedDays = new Set(data.completedDays || [1]);
      }
    } catch (e) {
      console.warn('[SleepyCourse] Could not load progress:', e);
    }
  }

  saveProgress() {
    try {
      const data = {
        currentDay: this.currentDay,
        completedDays: Array.from(this.completedDays)
      };
      localStorage.setItem('somnia_sleepy_course_progress', JSON.stringify(data));
    } catch (e) {
      console.warn('[SleepyCourse] Could not save progress:', e);
    }
  }

  completeDay(dayNumber) {
    this.completedDays.add(dayNumber);
    if (dayNumber < 30) {
      this.currentDay = Math.max(this.currentDay, dayNumber + 1);
    }
    this.saveProgress();
    if (window.Haptics) window.Haptics.success();
  }

  selectDay(dayNumber) {
    this.currentDay = dayNumber;
    this.saveProgress();
    if (window.Haptics) window.Haptics.selection();
  }

  getProgressStats() {
    const total = 30;
    const completed = this.completedDays.size;
    const percent = Math.round((completed / total) * 100);
    return { total, completed, percent, currentDay: this.currentDay };
  }

  getDay(dayNumber) {
    return SLEEPY_COURSE_DATA.find(d => d.day === dayNumber) || SLEEPY_COURSE_DATA[0];
  }
}

window.sleepyCourse = new SleepyCourseEngine();
